"""Local filesystem storage for bilag documents (development).

Not for production: a Cloudflare Container's disk is ephemeral, so anything
written here is gone when the instance sleeps. Production uses R2 with
``jurisdiction=eu`` — see :mod:`myntos.storage.r2`.

The key decides where a byte lands on disk, and it is generated by
:mod:`myntos.storage.keys`; :meth:`LocalDocumentStorage.load` re-checks its
shape before opening anything.
"""

from __future__ import annotations

import asyncio
import uuid
from pathlib import Path

from myntos.storage.base import ObjectNotFoundError
from myntos.storage.keys import new_key, validate_derived_key, validate_key


class LocalDocumentStorage:
    """Stores documents as files under ``root``."""

    def __init__(self, root: Path) -> None:
        self._root = root

    def _path(self, key: str) -> Path:
        return self._root / validate_key(key)

    async def save(self, *, content: bytes, filename: str, content_type: str) -> str:
        # filename is accepted for interface compatibility and deliberately
        # unused: the caller keeps it in the database, we never put it on disk.
        del filename
        key = new_key(content_type)
        path = self._path(key)
        await asyncio.to_thread(path.parent.mkdir, parents=True, exist_ok=True)
        await asyncio.to_thread(self._write_new, path, content)
        return key

    @staticmethod
    def _write_new(path: Path, content: bytes) -> None:
        # "xb" rather than "wb": a key collision must fail loudly instead of
        # overwriting a document we are legally required to keep.
        with path.open("xb") as handle:
            handle.write(content)

    async def save_derived(self, key: str, *, content: bytes, content_type: str) -> None:
        del content_type
        path = self._root / validate_derived_key(key)
        await asyncio.to_thread(path.parent.mkdir, parents=True, exist_ok=True)
        await asyncio.to_thread(self._replace, path, content)

    @staticmethod
    def _replace(path: Path, content: bytes) -> None:
        # Written beside and renamed over, so a reader never sees half a
        # thumbnail while two requests are making the same one.
        partial = path.with_name(f".{path.name}.{uuid.uuid4().hex}")
        partial.write_bytes(content)
        partial.replace(path)

    async def load(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return await asyncio.to_thread(path.read_bytes)
        except FileNotFoundError as error:
            raise ObjectNotFoundError(f"dokumentet {key} finnes ikke i lageret") from error
